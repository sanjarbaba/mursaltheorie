function nativePashto(row) {
  const prompt = row?.prompt?.ps;
  const options = Array.isArray(row?.options)
    ? row.options.map(option => typeof option === 'object' ? option?.ps : null)
    : [];
  return typeof prompt === 'string' && prompt.trim() && (!row.options?.length || options.every(Boolean))
    ? { prompt, options }
    : null;
}

function questionNumber(row) {
  const match = String(row?.external_key || '').match(/q(\d+)$/i);
  return match ? Number(match[1]) : null;
}

function translatedLesson(lessonId, type) {
  const suffix = type ? ':' + type : '';
  const stored = globalThis.MT_PASHTO?.['lesson:' + lessonId + suffix];
  if (stored) return stored;
  if (!type) return EARLY_LESSONS[lessonId]?.title || '';
  return type === 'rule' ? (EARLY_LESSONS[lessonId]?.rule || '') : (EARLY_LESSONS[lessonId]?.tip || '');
}

function placeCorrect(correct, value, count = 3) {
  const result = UNSAFE.slice(0, Math.max(2, count));
  while (result.length < count) result.push('ناخوندي کار کول');
  const index = Number.isInteger(Number(correct)) ? Number(correct) : 0;
  result[Math.min(Math.max(index, 0), count - 1)] = value;
  return result.slice(0, count);
}

function generatedQuestion(row, number) {
  const lessonId = Math.floor((number - 113) / 6) + 1;
  if (lessonId < 1 || lessonId > 150) return null;
  const variant = ((number - 113) % 6) + 1;
  const title = translatedLesson(lessonId) || ('درس ' + lessonId);
  const rule = translatedLesson(lessonId, 'rule') || 'لومړی ټول ترافیکي حالت، نښې، کرښې او نور د لارې کاروونکي وګورئ.';
  const tip = translatedLesson(lessonId, 'exam_tip') || 'په ازموینه کې د ټول انځور له کتلو وروسته تر ټولو خوندي ځواب وټاکئ.';
  const count = Math.max(2, Array.isArray(row.options) ? row.options.length : 3);
  if (variant === 1) return { prompt: 'د «' + title + '» په حالت کې کوم کار سم دی؟', options: placeCorrect(row.correct_option, rule, count) };
  if (variant === 2) return { prompt: 'د «' + title + '» په دې حالت کې سم عمل کوم دی؟', options: placeCorrect(row.correct_option, rule, count) };
  if (variant === 3) return { prompt: 'د «' + title + '» لپاره د ازموینې غوره لارښوونه کومه ده؟', options: placeCorrect(row.correct_option, tip, count) };
  if (variant === 4) return { prompt: 'د «' + title + '» په اړه ټول سم ځوابونه وټاکئ.', options: [rule, tip, 'له کتلو پرته سمدستي او ناخوندي عمل وکړئ'] };
  if (variant === 5) {
    const isTrue = Number(row.correct_option) === 0;
    return { prompt: isTrue ? ('د «' + title + '» په حالت کې دا خبره سمه ده: ' + rule) : ('د «' + title + '» په حالت کې د نښو او نورو د لارې کاروونکو کتلو ته اړتیا نشته.'), options: ['سم','ناسم'] };
  }
  return { prompt: 'انځور ته وګورئ. د «' + title + '» په حالت کې تر ټولو خوندي تشریح کومه ده؟', options: placeCorrect(row.correct_option, rule, count) };
}

export function pashtoQuestion(row) {
  const native = nativePashto(row);
  if (native) return native;
  const number = questionNumber(row);
  if (number && number <= 112 && BASE[number]) {
    return { prompt: BASE[number][0], options: BASE[number][1] };
  }
  return number ? generatedQuestion(row, number) : null;
}

export function pashtoExplanation(row) {
  const native = row?.explanation?.ps;
  if (typeof native === 'string' && native.trim()) return native;
  const translated = pashtoQuestion(row);
  if (!translated) return 'سم ځواب د ترافیکي قانون او خوندي چلند له مخې ټاکل کېږي.';
  const number = questionNumber(row);
  if (number && NUMERIC_ANSWERS[number]) return 'سم عددي ځواب ' + NUMERIC_ANSWERS[number] + ' دی.';
  const raw = Array.isArray(row.correct_answer) ? row.correct_answer : [];
  const indexes = raw.length ? raw.map(Number) : [Number(row.correct_option)];
  const answers = indexes.map(index => translated.options?.[index]).filter(Boolean);
  return answers.length
    ? 'د ترافیکي قانون له مخې سم ځواب' + (answers.length > 1 ? 'ونه' : '') + ': ' + answers.join('، ') + '.'
    : 'سم ځواب د ترافیکي قانون او خوندي چلند له مخې ټاکل کېږي.';
}

