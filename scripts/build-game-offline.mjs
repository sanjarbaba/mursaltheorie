import {readdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(fileURLToPath(new URL('../game/',import.meta.url)));
async function walk(dir){const entries=await readdir(dir,{withFileTypes:true});return (await Promise.all(entries.map(e=>e.isDirectory()?walk(path.join(dir,e.name)):path.join(dir,e.name)))).flat();}
const files=(await walk(root)).filter(f=>path.basename(f)!=='sw.js').sort();
const hash=createHash('sha256');for(const f of files)hash.update(await readFile(f));
const cache='mursal-hero-'+hash.digest('hex').slice(0,12);
const assets=['./',...files.map(f=>'./'+path.relative(root,f).split(path.sep).join('/'))];
await writeFile(path.join(root,'sw.js'),`// Generated by scripts/build-game-offline.mjs. Change source, then run npm run build.
const CACHE=${JSON.stringify(cache)};
const ASSETS=${JSON.stringify(assets)};
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS)).then(()=>self.skipWaiting())));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(k=>k.startsWith('mursal-hero-')&&k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{if(event.request.method!=='GET'||new URL(event.request.url).origin!==self.location.origin)return;const scope=new URL(self.registration.scope);if(!new URL(event.request.url).pathname.startsWith(scope.pathname))return;if(event.request.mode==='navigate'){event.respondWith(fetch(event.request).catch(()=>caches.match(new URL('./index.html',scope).href)));return;}event.respondWith(caches.match(event.request).then(cached=>cached||fetch(event.request)));});
`);
console.log(`Offline build: ${files.length} files, ${cache}`);
